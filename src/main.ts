import { renderAdminListingDetail } from "./pages/admin/listing-detail";
import { renderAdminLeases } from "./pages/admin/leases";
import { renderAdminLeaseDetail } from "./pages/admin/lease-detail";
import { renderAdminPayments } from "./pages/admin/payments";
import { renderAdminDocuments } from "./pages/admin/documents";
import { renderAdminMaintenance } from "./pages/admin/maintenance";
import { renderAdminMaintenanceDetail } from "./pages/admin/maintenance-detail";
import { renderAdminTenants } from "./pages/admin/tenants";

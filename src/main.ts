registerRoute({ path: "/tenant/documents", roles: ["tenant"], entitlement: "portal.tenant", render: renderTenantDocuments });
registerRoute({ path: "/tenant/maintenance", roles: ["tenant"], entitlement: "portal.tenant", render: renderTenantMaintenance });

registerRoute({ path: "/admin/leases/:id", roles: ["admin", "agent"], render: renderAdminLeaseDetail });
registerRoute({ path: "/admin/payments", roles: ["admin", "agent"], render: renderAdminPayments });
registerRoute({ path: "/admin/documents", roles: ["admin", "agent"], render: renderAdminDocuments });
registerRoute({ path: "/admin/maintenance", roles: ["admin", "agent"], render: renderAdminMaintenance });
registerRoute({ path: "/admin/maintenance/:id", roles: ["admin", "agent"], render: renderAdminMaintenanceDetail });

import { renderOwnerDocuments } from "./pages/owner/documents";
import { renderTenantDashboard } from "./pages/tenant/dashboard";
import { renderTenantLease } from "./pages/tenant/lease";
import { renderTenantPayments } from "./pages/tenant/payments";
